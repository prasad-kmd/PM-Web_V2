/**
 * The three columns now come from `lib/nav.ts`, which is also what the navbar,
 * the sidebar and the mobile dock read. The footer previously carried its own
 * copies, and they had drifted: ten of these labels pointed at pages that were
 * never built, and two (`/feed.xml`, `/status`) pointed at routes that do not
 * exist at all. Nothing compared the lists, so nothing noticed.
 */
type FooterLink = {
  readonly label: string;
  readonly href: string;
  /** Present on planned routes; `"shipped"` for a link that already exists. */
  readonly phase?: string;
};

const SOCIALS = [
  { icon: Github, href: siteConfig.socialLinks.github, label: "GitHub" },
  { icon: Twitter, href: siteConfig.socialLinks.twitter, label: "Twitter" },
  { icon: Linkedin, href: siteConfig.socialLinks.linkedin, label: "LinkedIn" },
  // Was `/feed.xml`, which has never existed — the feed is generated by
  // `app/rss.xml/route.ts`. A silent 404 behind the RSS icon.
  { icon: Rss, href: "/rss.xml", label: "RSS Feed" },
  { icon: Mail, href: "/contact", label: "Contact" },
] as const;

function FooterColumn({
  icon: Icon,
  title,
  links,
}: {
  icon: typeof Terminal;
  title: string;
  links: ReadonlyArray<FooterLink>;
}) {
  return (
    <div>
      <h3 className="mb-4 flex items-center gap-2 text-xs font-semibold uppercase tracking-widest text-ink">
        <Icon className="size-4 text-primary" strokeWidth={1.5} aria-hidden />{" "}
        {title}
      </h3>
      <ul className="space-y-2.5">
        {links.map((link) => {
          // A planned page is rendered as text, not as a link.
          //
          // Linking to a route that does not exist is what put ten 404s in this
          // column. Text cannot be clicked, so it cannot disappoint — and it is
          // deliberately *not* focusable, because an unreachable element in the
          // tab order is its own accessibility bug. The label stays so the
          // intended shape of the site is still visible.
          const planned =
            link.phase !== undefined && link.phase !== "shipped";

          return (
            <li key={link.href}>
              {planned ? (
                <span className="flex items-center gap-2 font-body text-[13px] text-muted-foreground/60">
                  {link.label}
                  <span className="rounded-full border border-border/70 px-1.5 py-px text-[10px] uppercase tracking-wide text-muted-foreground/70">
                    soon
                  </span>
                </span>
              ) : (
                <Link
                  href={link.href}
                  className="group flex items-center font-body text-[13px] text-muted-foreground transition-colors hover:text-primary"
                >
                  {link.label}
                  <ArrowUpRight className="ml-1 size-3 -translate-y-1 opacity-0 transition-all group-hover:translate-y-0 group-hover:opacity-100" />
                </Link>
              )}
            </li>
          );
        })}
      </ul>
    </div>
  );
}

